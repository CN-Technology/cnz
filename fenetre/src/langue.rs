#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn traductions_completes() {
        // Same number of "{}" in every language, and no duplicate key.
        for l in TEXTES {
            let n = l[0].matches("{}").count();
            assert!(l.iter().all(|x| x.matches("{}").count() == n && !x.is_empty()), "{}", l[0]);
            assert_eq!(TEXTES.iter().filter(|m| m[0] == l[0]).count(), 1, "{}", l[0]);
        }
    }

    #[test]
    fn arabe_lie_et_retourne() {
        // "لا": the isolated lam-alif ligature.
        assert_eq!(lier("\u{644}\u{627}"), "\u{FEFB}");
        // "تم": initial tā' then final mīm; displayed right to left.
        assert_eq!(visuel("\u{62A}\u{645}"), "\u{FEE2}\u{FE97}");
        // The number and the unit keep their direction, the parenthesis is mirrored.
        assert_eq!(visuel("\u{62A}\u{645} (95 KB)"), "(95 KB) \u{FEE2}\u{FE97}");
    }

    #[test]
    fn pluriels() {
        ACTUELLE.store(RUSSE, Ordering::Relaxed);
        assert_eq!([1, 3, 5, 11, 21, 22].map(fichiers), ["1 файл", "3 файла", "5 файлов", "11 файлов", "21 файл", "22 файла"]);
        ACTUELLE.store(UKRAINIEN, Ordering::Relaxed);
        assert_eq!([1, 4, 7].map(fichiers), ["1 файл", "4 файли", "7 файлів"]);
        ACTUELLE.store(0, Ordering::Relaxed);
    }
}
