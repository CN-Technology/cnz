//! Window languages: French, English, Spanish, German, Italian, Portuguese
//! (Brazil), Russian, Simplified Chinese, Japanese, Dutch, Polish, Turkish,
//! Arabic, Indonesian, Vietnamese, Korean, Ukrainian, Swahili, Persian and
//! Urdu. On first launch, the system language; the choice made in the top
//! bar is then kept in a small file (`%APPDATA%\CNZ\langue`, or
//! `~/.config/cnz/langue`).
//!
//! UI texts are written in French in the code; `t` looks up their
//! translation in `TEXTES` (French is kept when there is none). The
//! library's error messages stay in French.
//!
//! Arabic (and Persian, Urdu): egui neither joins letters nor writes right
//! to left. Arabic text is therefore converted before display (`visuel`):
//! each letter takes its joined form (Unicode presentation forms, present in
//! the font), then the line is put back into display order, runs of Latin
//! characters and numbers keeping their direction.

use std::collections::HashMap;
use std::path::PathBuf;
use std::sync::atomic::{AtomicUsize, Ordering};
use std::sync::Mutex;

pub const NOMS: [&str; 20] = [
    "Français", "English", "Español", "Deutsch", "Italiano", "Português", "Русский", "中文", "日本語", "Nederlands", "Polski", "Türkçe", "العربية",
    "Bahasa Indonesia", "Tiếng Việt", "한국어", "Українська", "Kiswahili", "فارسی", "اردو",
];
const CODES: [&str; 20] = ["fr", "en", "es", "de", "it", "pt", "ru", "zh", "ja", "nl", "pl", "tr", "ar", "id", "vi", "ko", "uk", "sw", "fa", "ur"];
pub const RUSSE: usize = 6;
pub const JAPONAIS: usize = 8;
const POLONAIS: usize = 10;
const ARABE: usize = 12;
pub const VIETNAMIEN: usize = 14;
pub const COREEN: usize = 15;
pub const UKRAINIEN: usize = 16;
const PERSAN: usize = 18;
const OURDOU: usize = 19;

/// Languages written right to left, in Arabic script.
fn droite_a_gauche(i: usize) -> bool {
    [ARABE, PERSAN, OURDOU].contains(&i)
}

/// Index of the current language in `NOMS` (also read by worker threads).
static ACTUELLE: AtomicUsize = AtomicUsize::new(0);

pub fn actuelle() -> usize {
    ACTUELLE.load(Ordering::Relaxed)
}

/// Name of a language in the selector, written in that language.
pub fn nom(i: usize) -> String {
    if droite_a_gauche(i) {
        visuel(NOMS[i])
    } else {
        NOMS[i].to_string()
    }
}

/// Folder of the window settings (language, recent archives).
pub fn dossier_reglages() -> Option<PathBuf> {
    if cfg!(windows) {
        std::env::var_os("APPDATA").map(|d| PathBuf::from(d).join("CNZ"))
    } else {
        let base = std::env::var_os("XDG_CONFIG_HOME").map(PathBuf::from).or_else(|| std::env::var_os("HOME").map(|h| PathBuf::from(h).join(".config")));
        base.map(|d| d.join("cnz"))
    }
}

fn fichier() -> Option<PathBuf> {
    dossier_reglages().map(|d| d.join("langue"))
}

/// At launch: the saved choice, otherwise the system language, otherwise French.
pub fn charger() {
    let gardee = fichier().and_then(|f| std::fs::read_to_string(f).ok());
    let code = gardee.or_else(sys_locale::get_locale).unwrap_or_default().trim().to_ascii_lowercase();
    if let Some(i) = CODES.iter().position(|c| code.starts_with(c)) {
        ACTUELLE.store(i, Ordering::Relaxed);
    }
}

/// Choice made in the top bar, kept for the next launches.
pub fn choisir(i: usize) {
    ACTUELLE.store(i, Ordering::Relaxed);
    if let Some(f) = fichier() {
        if let Some(d) = f.parent() {
            let _ = std::fs::create_dir_all(d);
        }
        let _ = std::fs::write(f, CODES[i]);
    }
}

/// Translation as written in the table (logical order for Arabic).
fn brut(fr: &'static str) -> &'static str {
    let i = actuelle();
    if i == 0 {
        return fr;
    }
    TEXTES.iter().find(|l| l[0] == fr).map_or(fr, |l| l[i])
}

fn remplir(modele: &str, args: &[&dyn std::fmt::Display]) -> String {
    let mut morceaux = modele.split("{}");
    let mut s = morceaux.next().unwrap_or_default().to_string();
    let mut args = args.iter();
    for m in morceaux {
        if let Some(a) = args.next() {
            s.push_str(&a.to_string());
        }
        s.push_str(m);
    }
    s
}

/// Translation of a text written in French, ready to display.
pub fn t(fr: &'static str) -> &'static str {
    if !droite_a_gauche(actuelle()) {
        return brut(fr);
    }
    // Conversion done once per text, then kept.
    static FAITS: Mutex<Option<HashMap<&'static str, &'static str>>> = Mutex::new(None);
    let mut faits = FAITS.lock().unwrap();
    faits.get_or_insert_with(HashMap::new).entry(fr).or_insert_with(|| Box::leak(visuel(brut(fr)).into_boxed_str()))
}

/// Translation, then each `{}` replaced by the next argument; ready to
/// display. Arguments must be raw (not already passed through `t`).
pub fn tf(fr: &'static str, args: &[&dyn std::fmt::Display]) -> String {
    let s = remplir(brut(fr), args);
    if droite_a_gauche(actuelle()) {
        visuel(&s)
    } else {
        s
    }
}

/// Name of a library work phase ("compression"…).
pub fn phase(nom: &str) -> String {
    let bas = nom.to_lowercase();
    let i = actuelle();
    let s = PHASES.iter().find(|l| l[0] == bas).map_or(bas, |l| l[i].to_string());
    if droite_a_gauche(i) {
        visuel(&s)
    } else {
        s
    }
}

/// "1 file", "3 files", raw (to pass as an argument of `tf`).
pub fn fichiers(n: u64) -> String {
    // Russian, Ukrainian and Polish: three forms (1; 2 to 4; 5 and more,
    // 11 to 14).
    let (unite, dizaine) = (n % 10, n % 100);
    let peu = (2..=4).contains(&unite) && !(12..=14).contains(&dizaine);
    match actuelle() {
        RUSSE => format!("{n} {}", if unite == 1 && dizaine != 11 { "файл" } else if peu { "файла" } else { "файлов" }),
        UKRAINIEN => format!("{n} {}", if unite == 1 && dizaine != 11 { "файл" } else if peu { "файли" } else { "файлів" }),
        POLONAIS => format!("{n} {}", if n == 1 { "plik" } else if peu { "pliki" } else { "plików" }),
        i => {
            let pluriel = if i == 0 { n > 1 } else { n != 1 };
            remplir(brut(if pluriel { "{} fichiers" } else { "{} fichier" }), &[&n])
        }
    }
}

/// Readable size: units and decimal separator of the language.
pub fn taille(n: u64) -> String {
    let unites = match actuelle() {
        0 => ["Go", "Mo", "Ko", "octets"],
        3 => ["GB", "MB", "KB", "Byte"],
        4 => ["GB", "MB", "KB", "byte"],
        RUSSE | UKRAINIEN => ["ГБ", "МБ", "КБ", "байт"],
        COREEN => ["GB", "MB", "KB", "바이트"],
        7 => ["GB", "MB", "KB", "字节"],
        JAPONAIS => ["GB", "MB", "KB", "バイト"],
        11 => ["GB", "MB", "KB", "bayt"],
        _ => ["GB", "MB", "KB", "bytes"],
    };
    let n = n as f64;
    let s = if n >= 1e9 {
        format!("{:.2} {}", n / 1e9, unites[0])
    } else if n >= 1e6 {
        format!("{:.1} {}", n / 1e6, unites[1])
    } else if n >= 1e3 {
        format!("{:.0} {}", n / 1e3, unites[2])
    } else {
        format!("{n} {}", unites[3])
    };
    decimal(s)
}

/// Number with one decimal, with a comma except in English, Chinese,
/// Japanese, Korean, Swahili and the Arabic-script languages.
pub fn nombre(x: f64) -> String {
    decimal(format!("{x:.1}"))
}

fn decimal(s: String) -> String {
    if [1, 7, JAPONAIS, COREEN, 17].contains(&actuelle()) || droite_a_gauche(actuelle()) {
        s
    } else {
        s.replace('.', ",")
    }
}

