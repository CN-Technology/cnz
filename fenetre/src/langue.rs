/// Lam followed by alif: a single ligature (isolated; +1 for the final form).
const LAM_ALIF: &[(char, u32)] = &[('\u{622}', 0xFEF5), ('\u{623}', 0xFEF7), ('\u{625}', 0xFEF9), ('\u{627}', 0xFEFB)];

fn lettre(c: char) -> Option<(u32, bool)> {
    LETTRES.iter().find(|l| l.0 == c).map(|l| (l.1, l.2))
}

/// Joined letters: each Arabic letter replaced by its form given its neighbours.
fn lier(s: &str) -> String {
    let c: Vec<char> = s.chars().collect();
    let mut out = String::new();
    // Does the previous letter join this one?
    let mut lie_avant = false;
    let mut i = 0;
    while i < c.len() {
        let Some((forme, deux_cotes)) = lettre(c[i]) else {
            out.push(c[i]);
            lie_avant = false;
            i += 1;
            continue;
        };
        if c[i] == '\u{644}' {
            if let Some(&(_, lig)) = c.get(i + 1).and_then(|n| LAM_ALIF.iter().find(|l| l.0 == *n)) {
                out.push(char::from_u32(lig + lie_avant as u32).unwrap());
                lie_avant = false;
                i += 2;
                continue;
            }
        }
        let lie_apres = deux_cotes && c.get(i + 1).is_some_and(|n| lettre(*n).is_some());
        let decalage = match (lie_avant, lie_apres) {
            (false, false) => 0,
            (true, false) => 1,
            (false, true) => 2,
            (true, true) => 3,
        };
        out.push(char::from_u32(forme + decalage).unwrap());
        lie_avant = deux_cotes;
        i += 1;
    }
    out
}

fn est_arabe(c: char) -> bool {
    matches!(c as u32, 0x600..=0x6FF | 0xFB50..=0xFDFF | 0xFE70..=0xFEFF)
}

/// Arabic text ready for egui: joined letters, and each line put back into
/// display order (right to left), runs of Latin letters, digits, paths…
/// keeping their direction.
pub fn visuel(s: &str) -> String {
    s.split('\n').map(|ligne| ligne_visuelle(&lier(ligne))).collect::<Vec<_>>().join("\n")
}

fn ligne_visuelle(ligne: &str) -> String {
    let c: Vec<char> = ligne.chars().collect();
    // Strong direction of each character: Some(true) left to right, Some(false)
    // Arabic, None neutral (spaces, punctuation).
    let fort: Vec<Option<bool>> = c.iter().map(|&x| if est_arabe(x) { Some(false) } else if x.is_alphanumeric() { Some(true) } else { None }).collect();
    // A neutral between two left-to-right runs belongs to them
    // ("95 KB", "/s/donnees/projet.zip"); otherwise it follows the Arabic.
    let sens: Vec<bool> = (0..c.len())
        .map(|i| {
            fort[i].unwrap_or_else(|| {
                let avant = fort[..i].iter().rev().find_map(|x| *x);
                let apres = fort[i + 1..].iter().find_map(|x| *x);
                avant == Some(true) && apres == Some(true)
            })
        })
        .collect();
    let mut passages: Vec<(bool, Vec<char>)> = Vec::new();
    for (x, g) in c.into_iter().zip(sens) {
        match passages.last_mut() {
            Some((s, v)) if *s == g => v.push(x),
            _ => passages.push((g, vec![x])),
        }
    }
    let mut out = String::new();
    for (gauche, v) in passages.into_iter().rev() {
        if gauche {
            out.extend(v);
        } else {
            out.extend(v.into_iter().rev().map(|x| match x {
                '(' => ')',
                ')' => '(',
                '[' => ']',
                ']' => '[',
                '«' => '»',
                '»' => '«',
                x => x,
            }));
        }
    }
    out
}

